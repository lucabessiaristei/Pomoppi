// tools/make-launcher.js — generates a double-clickable macOS .app bundle that
// launches Pomoppi without a terminal (SPEC.md §10). Hand-rolled bundle: no
// packager, no npm install. Destination defaults to /Applications/Pomoppi.app,
// or process.argv[2] if given -- /Applications because that is the first place
// lib/login-item.js looks for the bundle, so building and launching at login
// agree on one copy instead of racing a stale one left on the Desktop.
//
// This is a launcher for the WORKING COPY, not a distributable app: the
// bundle's shell script bakes in absolute paths into this repo and its
// node_modules/electron. Moving or deleting the repo breaks the bundle;
// re-run this script to regenerate it in place.
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const REPO_ROOT = path.join(__dirname, '..');
const BUNDLE_ID = 'it.lucabessiaristei.pomoppi';

// The Liquid Glass app icon (macOS 26), authored in Icon Composer. assets/
// holds two variants of the same drawing -- pomoppi-clear.icon sets
// "glass": true on its layer, pomoppi-simple.icon sets it false. Swap the
// name here to switch which one the bundle ships.
const GLASS_ICON_SOURCE = 'pomoppi-clear.icon';

// actool must see the .icon bundle named after whatever --app-icon says.
const GLASS_ICON_NAME = 'AppIcon';

// actool ships inside Xcode.app, NOT the Command Line Tools, so it is often
// absent -- buildGlassIcon() degrades to the sips/iconutil .icns path when
// it is. Probed via xcrun first so a switched xcode-select wins.
const ACTOOL_FALLBACK = '/Applications/Xcode.app/Contents/Developer/usr/bin/actool';

// actool's output, committed next to the .icon source. Xcode is a ~15GB
// install for one build step, and a compiled catalog is just a file -- so the
// build ships the layered icon on a machine that has never had Xcode. A run
// that DOES find actool rewrites these, so the .icon stays the source of
// truth: edit it in Icon Composer, rebuild once anywhere with Xcode, commit.
const GLASS_CACHE_CAR = 'AppIcon.car';
const GLASS_CACHE_ICNS = 'AppIcon.icns';

const dest = path.resolve(process.argv[2] || path.join('/Applications', 'Pomoppi.app'));

// Resolve the Electron binary the supported way: path.txt holds a path
// relative to node_modules/electron/dist/, not a fixed inner layout — reading
// it (rather than hardcoding "Electron.app/Contents/MacOS/Electron") keeps
// this working across Electron versions/platforms without a dependency.
function resolveElectronBinary() {
  const electronDir = path.join(REPO_ROOT, 'node_modules', 'electron');
  const pathTxt = path.join(electronDir, 'path.txt');
  if (!fs.existsSync(pathTxt)) {
    console.error(
      `Cannot find ${pathTxt}. Run "npm install" in ${REPO_ROOT} first.`
    );
    process.exit(1);
  }
  const rel = fs.readFileSync(pathTxt, 'utf8').trim();
  const binary = path.join(electronDir, 'dist', rel);
  if (!fs.existsSync(binary)) {
    console.error(
      `Electron binary not found at ${binary} (from ${pathTxt}). Run "npm install" in ${REPO_ROOT} first.`
    );
    process.exit(1);
  }
  return binary;
}

// Single-quote a path for embedding in the /bin/sh script, escaping any
// embedded single quotes.
function shQuote(str) {
  return `'${str.replace(/'/g, `'\\''`)}'`;
}

function xmlEscape(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

// Before touching anything at `dest`, make sure it's actually a bundle we
// generated previously — never delete a stray file/folder that happens to
// sit at the destination path.
function removeExistingBundleIfOurs(bundleDir) {
  if (!fs.existsSync(bundleDir)) return;

  const infoPlist = path.join(bundleDir, 'Contents', 'Info.plist');
  let isOurs = false;
  if (fs.statSync(bundleDir).isDirectory() && fs.existsSync(infoPlist)) {
    const contents = fs.readFileSync(infoPlist, 'utf8');
    isOurs = contents.includes('<key>CFBundleIdentifier</key>') && contents.includes(BUNDLE_ID);
  }

  if (!isOurs) {
    console.error(
      `Refusing to overwrite ${bundleDir}: it exists but doesn't look like a Pomoppi.app bundle ` +
        `(no Contents/Info.plist with CFBundleIdentifier ${BUNDLE_ID}). Remove it manually or choose a different destination.`
    );
    process.exit(1);
  }

  fs.rmSync(bundleDir, { recursive: true, force: true });
}

function writeLauncherScript(macosDir, electronBinary) {
  const scriptPath = path.join(macosDir, 'Pomoppi');
  const script = [
    '#!/bin/sh',
    '# Generated by tools/make-launcher.js — launches the Pomoppi working copy.',
    '# Regenerate with "npm run launcher" after moving the repo or reinstalling Electron.',
    '#',
    "# Do NOT change this to `exec`. `exec` replaces this shell process, so the",
    '# process LaunchServices launched for Pomoppi.app *becomes* Electron',
    "# mid-flight — and under that path, Electron's NSStatusItem never appears",
    '# in the menu bar (tray icon silently missing), even though the app runs',
    '# fine and every other check (icon load, Tray object, LSUIElement, bundle',
    '# identity) is identical to running via `npm start`. Backgrounding Electron',
    "# and `wait`-ing keeps this stub alive as the app's process for as long as",
    '# it runs — same shape as `npm start` spawning Electron as a child — so',
    '# LaunchServices and Electron both see a normal child launch and the tray',
    '# icon registers correctly.',
    `${shQuote(electronBinary)} ${shQuote(REPO_ROOT)} "$@" &`,
    'wait',
    '',
  ].join('\n');
  fs.writeFileSync(scriptPath, script);
  fs.chmodSync(scriptPath, 0o755);
}

// `icon` is whatever buildGlassIcon()/buildIcon() returned, or null: the
// CFBundleIcon* keys the bundle carries depend on which path produced the
// icon, so the plist is written after the icon, not before it.
function writeInfoPlist(contentsDir, version, icon) {
  let iconXml = '';
  if (icon && icon.iconFile) {
    iconXml += `\t<key>CFBundleIconFile</key>\n\t<string>${xmlEscape(icon.iconFile)}</string>\n`;
  }
  if (icon && icon.iconName) {
    // CFBundleIconName is what points LaunchServices at Assets.car, and so
    // at the layered icon. Without it macOS falls back to the flat .icns.
    iconXml += `\t<key>CFBundleIconName</key>\n\t<string>${xmlEscape(icon.iconName)}</string>\n`;
  }

  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleName</key>
	<string>Pomoppi</string>
	<key>CFBundleDisplayName</key>
	<string>Pomoppi</string>
	<key>CFBundleExecutable</key>
	<string>Pomoppi</string>
	<key>CFBundleIdentifier</key>
	<string>${xmlEscape(BUNDLE_ID)}</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
${iconXml}	<key>CFBundleShortVersionString</key>
	<string>${xmlEscape(version)}</string>
	<key>CFBundleVersion</key>
	<string>${xmlEscape(version)}</string>
	<key>LSUIElement</key>
	<true/>
</dict>
</plist>
`;
  fs.writeFileSync(path.join(contentsDir, 'Info.plist'), plist);
}

// actool lives in Xcode.app; `xcrun -f` finds it only when xcode-select
// points at a full Xcode rather than the Command Line Tools, so fall back to
// the standard install path before giving up.
function resolveActool() {
  try {
    const found = execFileSync('xcrun', ['-f', 'actool'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (found && fs.existsSync(found)) return found;
  } catch {
    // xcode-select points at the CLT, which has no actool. Not an error.
  }
  return fs.existsSync(ACTOOL_FALLBACK) ? ACTOOL_FALLBACK : null;
}

// Compiles assets/<GLASS_ICON_SOURCE> into the layered macOS 26 icon.
// Returns a descriptor for writeInfoPlist(), or null to fall through to the
// legacy buildIcon() path -- no missing tool or actool failure may break the
// build, same rule as buildIcon() below.
function buildGlassIcon(resourcesDir) {
  const source = path.join(REPO_ROOT, 'assets', GLASS_ICON_SOURCE);
  if (!fs.existsSync(source)) {
    console.error(`Note: assets/${GLASS_ICON_SOURCE} not found; using the .icns icon.`);
    return null;
  }
  const actool = resolveActool();
  if (!actool) {
    console.error('Note: actool not found (it needs full Xcode, not just the Command Line Tools); using the prebuilt catalog.');
    return null;
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pomoppi-glass-'));
  try {
    // The .icon bundle is passed to actool DIRECTLY, as its own input. This
    // is the whole trick: wrapping it in a .xcassets the way a pre-26 icon
    // set would be compiles cleanly and emits nothing at all, silently.
    const staged = path.join(tmpDir, `${GLASS_ICON_NAME}.icon`);
    fs.cpSync(source, staged, { recursive: true });
    const outDir = path.join(tmpDir, 'out');
    fs.mkdirSync(outDir);

    execFileSync(actool, [
      '--output-format', 'human-readable-text',
      '--app-icon', GLASS_ICON_NAME,
      '--output-partial-info-plist', path.join(tmpDir, 'partial.plist'),
      '--development-region', 'en',
      '--target-device', 'mac',
      // The layered icon is a macOS 26 feature; the .icns emitted next to it
      // is what older systems (and un-migrated surfaces) fall back to.
      '--minimum-deployment-target', '26.0',
      '--platform', 'macosx',
      '--compile', outDir,
      staged,
    ], { stdio: 'ignore' });

    const car = path.join(outDir, 'Assets.car');
    if (!fs.existsSync(car)) {
      console.error('Warning: actool emitted no Assets.car; using the .icns icon.');
      return null;
    }
    fs.copyFileSync(car, path.join(resourcesDir, 'Assets.car'));

    // actool emits a flat .icns from the same source for free. Ship it too,
    // so the bundle still has an icon everywhere the layered one isn't used.
    const icns = path.join(outDir, `${GLASS_ICON_NAME}.icns`);
    const gotIcns = fs.existsSync(icns);
    if (gotIcns) fs.copyFileSync(icns, path.join(resourcesDir, `${GLASS_ICON_NAME}.icns`));

    // Refresh the committed cache so the next Xcode-less build ships what
    // this compile just produced. A read-only checkout must not fail here:
    // the bundle already has its icon either way.
    try {
      fs.copyFileSync(car, path.join(REPO_ROOT, 'assets', GLASS_CACHE_CAR));
      if (gotIcns) fs.copyFileSync(icns, path.join(REPO_ROOT, 'assets', GLASS_CACHE_ICNS));
    } catch (err) {
      console.error(`Note: could not refresh assets/${GLASS_CACHE_CAR} (${err.message}).`);
    }

    return {
      iconFile: gotIcns ? GLASS_ICON_NAME : null,
      iconName: GLASS_ICON_NAME,
      label: `${path.join(resourcesDir, 'Assets.car')} (Liquid Glass, from ${GLASS_ICON_SOURCE})`,
    };
  } catch (err) {
    console.error(`Warning: could not compile ${GLASS_ICON_SOURCE} (${err.message}); using the .icns icon.`);
    return null;
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

// The Xcode-less path: ship the committed catalog as-is. Same descriptor as
// buildGlassIcon(), because the bundle ends up byte-identical either way.
function useCachedGlassIcon(resourcesDir) {
  const car = path.join(REPO_ROOT, 'assets', GLASS_CACHE_CAR);
  if (!fs.existsSync(car)) return null;
  fs.copyFileSync(car, path.join(resourcesDir, 'Assets.car'));

  const icns = path.join(REPO_ROOT, 'assets', GLASS_CACHE_ICNS);
  const gotIcns = fs.existsSync(icns);
  if (gotIcns) fs.copyFileSync(icns, path.join(resourcesDir, `${GLASS_ICON_NAME}.icns`));

  return {
    iconFile: gotIcns ? GLASS_ICON_NAME : null,
    iconName: GLASS_ICON_NAME,
    label: `${path.join(resourcesDir, 'Assets.car')} (Liquid Glass, prebuilt assets/${GLASS_CACHE_CAR})`,
  };
}

// Best-effort: a missing assets/icon.png or a failing sips/iconutil must
// never fail the whole build — the bundle still works with the system's
// generic app icon.
const ICONSET_SIZES = [
  ['icon_16x16.png', 16],
  ['icon_16x16@2x.png', 32],
  ['icon_32x32.png', 32],
  ['icon_32x32@2x.png', 64],
  ['icon_128x128.png', 128],
  ['icon_128x128@2x.png', 256],
  ['icon_256x256.png', 256],
  ['icon_256x256@2x.png', 512],
  ['icon_512x512.png', 512],
  ['icon_512x512@2x.png', 1024],
];

function buildIcon(resourcesDir) {
  const sourcePng = path.join(REPO_ROOT, 'assets', 'icon.png');
  if (!fs.existsSync(sourcePng)) {
    console.error('Warning: assets/icon.png not found (run "npm run icons"); bundle will have no icon.');
    return null;
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pomoppi-icon-'));
  try {
    const iconsetDir = path.join(tmpDir, 'icon.iconset');
    fs.mkdirSync(iconsetDir);
    for (const [name, size] of ICONSET_SIZES) {
      execFileSync('sips', ['-z', String(size), String(size), sourcePng, '--out', path.join(iconsetDir, name)], {
        stdio: 'ignore',
      });
    }
    const icnsPath = path.join(tmpDir, 'icon.icns');
    execFileSync('iconutil', ['-c', 'icns', iconsetDir, '-o', icnsPath], { stdio: 'ignore' });
    fs.copyFileSync(icnsPath, path.join(resourcesDir, 'icon.icns'));
    return { iconFile: 'icon', iconName: null, label: path.join(resourcesDir, 'icon.icns') };
  } catch (err) {
    console.error(`Warning: could not build icon.icns (${err.message}); continuing without an icon.`);
    return null;
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

function main() {
  const electronBinary = resolveElectronBinary();
  const pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf8'));

  removeExistingBundleIfOurs(dest);

  const contentsDir = path.join(dest, 'Contents');
  const macosDir = path.join(contentsDir, 'MacOS');
  const resourcesDir = path.join(contentsDir, 'Resources');
  fs.mkdirSync(macosDir, { recursive: true });
  fs.mkdirSync(resourcesDir, { recursive: true });

  writeLauncherScript(macosDir, electronBinary);
  // Icon before plist: the Liquid Glass path and the legacy one need
  // different CFBundleIcon* keys, so the plist can't be written until we
  // know which one produced the icon.
  const icon = buildGlassIcon(resourcesDir) || useCachedGlassIcon(resourcesDir) || buildIcon(resourcesDir);
  writeInfoPlist(contentsDir, pkg.version, icon);

  console.log(`Wrote ${dest}`);
  console.log(`  launcher: ${path.join(macosDir, 'Pomoppi')} -> ${electronBinary} ${REPO_ROOT}`);
  console.log(`  icon: ${icon ? icon.label : '(none)'}`);
}

main();
